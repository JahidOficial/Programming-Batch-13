// Math min and max functions
const min = Math.min(1, 2, 3, 4, 5);
const max = Math.max(1, 2, 3, 4, 5);

console.log('Min: ', min); // Output: 1
console.log('Max: ', max); // Output: 5


// math PI constant
console.log('PI: ', Math.PI);

// math abs function
console.log('Abs: ', Math.abs(-54));

// math round function
console.log('Round: ', Math.round(4.7)); // Output: 5

// math ceil function
console.log('Ceil: ', Math.ceil(4.2)); // Output: 5

// math floor function
console.log('Floor: ', Math.floor(4.7)); // Output: 4

// math random function
console.log('Random: ', Math.random()); // Output: A random number between 0 and 1